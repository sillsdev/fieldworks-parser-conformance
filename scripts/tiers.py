"""The tier of every conformance test case, computed (ADR 0009) and written into docs/grammars.md.

    python3 scripts/tiers.py            print the tier table
    python3 scripts/tiers.py --write    rewrite the generated block of docs/grammars.md
    python3 scripts/tiers.py --core     print the core tier, one id per line (what a consumer runs on every PR)

Never authored: a tier is not a key in words.yaml and never part of an id (Q5). It follows from data the suite holds.

  core        languages/*; a test case with a fieldworks/ witness; or one of the two carriers of a behaviour
              label (the label is an `exercises` construct today, and #75 replaces it; carriers are the test
              cases with that label, fewest words first, then id)
  regression  not core, and it has a row in status.yaml or 300 or more words
  extended    the rest

Consumers' own divergences are not recorded here: they live in the consumer's repo under its issue (ADR 0007).
Standard library plus PyYAML.
"""
import functools
import sys
from pathlib import Path

from suite import ROOT, fixture_dirs, fixture_id, load_words

GRAMMARS_MD = ROOT / "docs" / "grammars.md"
BEGIN = "<!-- tiers:begin (generated by scripts/tiers.py --write; do not edit by hand) -->"
END = "<!-- tiers:end -->"
CARRIERS_PER_LABEL = 2
REGRESSION_WORDS = 300
TIERS = ("core", "regression", "extended")


@functools.lru_cache(maxsize=None)
def facts(root: Path = ROOT) -> dict:
    """id -> {words, labels, witness} for every conformance test case."""
    found = {}
    for d in fixture_dirs(root):
        data = load_words(d / "words.yaml")
        labels = set()
        for word in data["words"]:
            labels.update(word.get("exercises") or [])
            for parse in word.get("parses") or []:
                labels.update(parse.get("exercises") or [])
        found[fixture_id(d, root)] = {
            "words": len(data["words"]),
            "labels": labels,
            "witness": (d / "fieldworks").is_dir(),
        }
    return found


def compute(root: Path = ROOT, excepted=None) -> dict:
    """id -> (tier, why). `excepted` is the set of test cases with a status.yaml row,"""
    import exceptions

    if excepted is None:
        excepted = {row["case"] for row in exceptions.load(root / "status.yaml")}
    found = facts(root)
    carriers = {}
    for label in sorted({l for f in found.values() for l in f["labels"]}):
        holders = sorted((f["words"], case) for case, f in found.items() if label in f["labels"])
        for _, case in holders[:CARRIERS_PER_LABEL]:
            carriers.setdefault(case, []).append(label)
    result = {}
    for case, f in found.items():
        why = []
        if case.startswith("languages/"):
            why.append("language profile")
        if f["witness"]:
            why.append("FieldWorks witness")
        if case in carriers:
            why.append("carries " + ", ".join(carriers[case]))
        if why:
            result[case] = ("core", "; ".join(why))
        elif case in excepted or f["words"] >= REGRESSION_WORDS:
            why = (["exception in status.yaml"] if case in excepted else []) + (
                [f"{f['words']} words"] if f["words"] >= REGRESSION_WORDS else [])
            result[case] = ("regression", "; ".join(why))
        else:
            result[case] = ("extended", "")
    return result


def block(tiers: dict) -> str:
    count = {t: sum(1 for tier, _ in tiers.values() if tier == t) for t in TIERS}
    lines = [
        BEGIN,
        "## Tier of every test case",
        "",
        "The tier says how often a consumer should run a test case: **core** on every pull request, **regression** and "
        "**extended** on the full run. It is computed by `scripts/tiers.py` from data the suite holds, never authored, "
        "and never part of an id; `scripts/check_grammars_md.py` fails when this table is stale. "
        "A test case is core when it is a language profile, has a FieldWorks witness, or is one "
        "of the two smallest carriers of a behaviour label (an `exercises` construct until #75 replaces it; "
        "fewest words first, then id). Otherwise it is regression when it has a row in `status.yaml` or 300 or more "
        "words, and extended when it has neither.",
        "",
        f"{count['core']} core, {count['regression']} regression, {count['extended']} extended.",
        "",
        "| test case | tier | why |",
        "| --- | --- | --- |",
    ]
    for case in sorted(tiers, key=lambda c: c.encode("utf-8")):
        tier, why = tiers[case]
        lines.append(f"| `{case}` | {tier} | {why} |")
    lines.append(END)
    return "\n".join(lines)


def current_block(text: str):
    start, end = text.find(BEGIN), text.find(END)
    if start < 0 or end < start:
        return None
    return text[start:end + len(END)]


def core(tiers: dict) -> list:
    return sorted((c for c, (t, _) in tiers.items() if t == "core"), key=lambda c: c.encode("utf-8"))


def main(argv=None) -> int:
    args = (sys.argv[1:] if argv is None else argv)
    tiers = compute()
    if "--core" in args:
        print("\n".join(core(tiers)))
        return 0
    if "--write" in args:
        text = GRAMMARS_MD.read_text(encoding="utf-8")
        old = current_block(text)
        new = block(tiers)
        if old is None:
            marker = "## Which engines run which grammars"
            text = text.replace(marker, new + "\n\n" + marker, 1)
        else:
            text = text.replace(old, new, 1)
        GRAMMARS_MD.write_text(text, encoding="utf-8")
        return 0
    print(block(tiers))
    return 0


if __name__ == "__main__":
    sys.exit(main())
